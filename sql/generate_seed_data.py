"""Regenerate sql/seed_data.sql from the raw CSVs in data/.

Blank CSV cells become SQL NULL (never an empty string), so
COUNT(rating) and COALESCE(discount_pct, 0) behave correctly in reports.sql.

Usage (from the repo root):  python sql/generate_seed_data.py
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "sql" / "seed_data.sql"

# Columns stored as numbers; everything else is quoted text.
NUMERIC = {"city_tier", "price", "quantity", "discount_pct", "rating", "returned"}
TABLES = ["customers", "products", "orders"]  # parents before child (FK order)


def sql_value(col, raw):
    if raw == "":
        return "NULL"
    if col in NUMERIC:
        return raw
    return "'" + raw.replace("'", "''") + "'"


def main():
    lines = [
        "-- =====================================================================",
        "-- Part 1, Task 2 — Seed data",
        "-- GENERATED by sql/generate_seed_data.py from data/*.csv — do not hand-edit.",
        "-- Blank CSV cells are loaded as NULL. Re-runnable: clears tables first.",
        "-- =====================================================================",
        "",
        "PRAGMA foreign_keys = ON;",
        "",
        "DELETE FROM orders;",
        "DELETE FROM customers;",
        "DELETE FROM products;",
        "",
        "BEGIN TRANSACTION;",
    ]
    for table in TABLES:
        with open(DATA / f"{table}.csv", newline="", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            cols = reader.fieldnames
            lines.append("")
            lines.append(f"-- {table}")
            for row in reader:
                values = ", ".join(sql_value(c, row[c]) for c in cols)
                lines.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({values});")
    lines += [
        "",
        "COMMIT;",
        "",
        "-- Verification: expect 45 / 16 / 180",
        "SELECT 'customers', COUNT(*) FROM customers;",
        "SELECT 'products',  COUNT(*) FROM products;",
        "SELECT 'orders',    COUNT(*) FROM orders;",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
